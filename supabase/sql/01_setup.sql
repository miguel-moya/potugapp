-- Fase 1 · Dashboard familiar · Tabla de prueba
-- Pegar entero en Supabase > SQL Editor > New query > Run

create table if not exists items (
  id bigint generated by default as identity primary key,
  name text not null,
  done boolean not null default false,
  created_at timestamptz not null default now()
);

-- Permisos explícitos (necesarios porque desactivamos "Automatically expose new tables")
grant select, insert, update, delete on table items to anon;
grant usage, select on all sequences in schema public to anon;

alter table items enable row level security;

-- SOLO PARA LA FASE 1: cualquiera con la dirección de la app puede leer y escribir.
-- En la Fase 2 lo cerraremos con usuarios de la familia.
create policy "fase1_select" on items for select to anon using (true);
create policy "fase1_insert" on items for insert to anon with check (true);
create policy "fase1_update" on items for update to anon using (true) with check (true);
create policy "fase1_delete" on items for delete to anon using (true);

insert into items (name) values ('Leche'), ('Pan'), ('Prueba desde Supabase');
