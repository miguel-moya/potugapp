-- Compra: grupos, básicos y lista. La leen y escriben solo la función "compra" (clave de servicio).
-- Pegar entero en Supabase > SQL Editor > New query > Run. Se puede volver a ejecutar sin romper nada.

create table if not exists compra_grupos (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  orden int not null default 0
);
create table if not exists compra_basicos (
  id bigint generated by default as identity primary key,
  grupo_id bigint not null references compra_grupos(id) on delete cascade,
  nombre text not null,
  orden int not null default 0,
  unique (grupo_id, nombre)
);
create table if not exists compra_lista (
  id text primary key,                      -- lo genera el aparato (sirve para reintentar sin duplicar)
  nombre text not null,
  basico_id bigint references compra_basicos(id) on delete set null,
  grupo_id bigint references compra_grupos(id) on delete set null,   -- null = «Otros»
  quien text,
  nota text,
  hecho boolean not null default false,
  creado timestamptz not null default now(),
  actualizado timestamptz not null default now()
);

-- Seguridad: activada y sin permisos públicos. Solo la clave de servicio (la función) entra.
alter table compra_grupos enable row level security;
alter table compra_basicos enable row level security;
alter table compra_lista enable row level security;
grant all on table compra_grupos, compra_basicos, compra_lista, calendario_cache to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Cerrar la tabla de prueba de la fase 1 (ya no la usa nadie)
drop policy if exists "fase1_select" on items;
drop policy if exists "fase1_insert" on items;
drop policy if exists "fase1_update" on items;
drop policy if exists "fase1_delete" on items;
revoke all on table items from anon;

